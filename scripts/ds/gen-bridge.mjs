// Generates src/styles/bridge.css from Tailwind's own theme file + the MASAR ramps below.
// Why: Tailwind inlines a literal colour for opacity utilities (bg-slate-100/70) when the theme value is a literal.
// Pointing the theme at a variable makes it emit color-mix(var(...)), so the scoped override reaches those classes too.
// Unscoped surfaces keep Tailwind's original value through the :root default.
import { readFileSync, writeFileSync } from 'node:fs';
const theme = readFileSync(new URL('../../node_modules/tailwindcss/theme.css', import.meta.url), 'utf8');
const shades = ['50','100','200','300','400','500','600','700','800','900','950'];
const orig = (fam, s) => {
  const m = new RegExp(`--color-${fam}-${s}:\\s*([^;]+);`).exec(theme);
  if (!m) throw new Error(`missing ${fam}-${s}`);
  return m[1].trim();
};
const slate = { 50:'#fafafa',100:'#f5f5f5',200:'#dcdcdc',300:'#8a8a8a',400:'#6b6b6b',500:'#6b6b6b',600:'#555555',700:'#444444',800:'#2b2b2b',900:'#171717',950:'#000000' };
const blue = { 50:'#e8f5ef',100:'#d5ede2',200:'#b3e0cc',300:'#7cc9a8',400:'#14c88a',500:'#0a7d56',600:'#0b3d2e',700:'#0f4f3b',800:'#0b3d2e',900:'#082b21',950:'#04170f' };
const fams = { slate, blue };
let out = `/*
 * GENERATED by scripts/ds/gen-bridge.mjs. Do not edit by hand. Scoped bridge (plan 5.3 Step A); removed in Phase 6.
 * Mapping keeps legacy meaning: slate-300 = control border (3:1), slate-400/500 = muted text (4.5:1),
 * blue-600 = primary fill and link colour. Hard-coded hex values (#14243A, bg-[#f6f8fb]) are NOT reached.
 */
@theme static {\n`;
for (const f of Object.keys(fams)) for (const s of shades) out += `  --color-${f}-${s}: var(--bridge-${f}-${s});\n`;
out += `}\n\n/* Unscoped default = Tailwind's original value, so surfaces that are not flipped do not change. */\n:root {\n`;
for (const f of Object.keys(fams)) for (const s of shades) out += `  --bridge-${f}-${s}: ${orig(f, s)};\n`;
out += `}\n\n[data-ds="masar"] {\n`;
for (const [f, map] of Object.entries(fams)) for (const s of shades) out += `  --bridge-${f}-${s}: ${map[s]};\n`;
// A custom property holding var() is resolved where it is DECLARED (:root), so changing --bridge-* here is not enough:
// the --color-* aliases must be declared again inside the scope or every plain bg-slate-900 keeps Tailwind's original navy.
for (const f of Object.keys(fams)) for (const s of shades) out += `  --color-${f}-${s}: var(--bridge-${f}-${s});\n`;
out += `}\n`;
writeFileSync(new URL('../../src/styles/bridge.css', import.meta.url), out);
console.log('bridge.css written');
